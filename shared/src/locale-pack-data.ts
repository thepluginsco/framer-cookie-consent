/**
 * The built-in translations of the default copy, one pack per language.
 *
 * This module is DATA for the editor (previews, placeholders) and for the runtime
 * build, which writes each pack to `runtime/dist/locales/<code>.json`. The runtime
 * bundle itself never imports it: a published site fetches only the one pack its
 * visitor needs (see `runtime/src/locale-loader.ts`).
 */

import {
  packCategoryWith,
  packLanguage,
  packTextWith,
  type LocalePack,
  type PackTextKey,
} from './locale-packs.js';
import type { CategoryStrings } from './config-schema.js';

/** Build the category block of a pack from `[label, description]` pairs. */
function cats(
  necessary: [string, string],
  analytics: [string, string],
  marketing: [string, string],
  preferences: [string, string],
): Record<string, CategoryStrings> {
  const c = (p: [string, string]): CategoryStrings => ({ label: p[0], description: p[1] });
  return { necessary: c(necessary), analytics: c(analytics), marketing: c(marketing), preferences: c(preferences) };
}

