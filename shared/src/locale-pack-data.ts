/** The built-in pack for a language tag, or `undefined` when none ships. */
export function localePack(lang: string): LocalePack | undefined {
  const code = packLanguage(lang);
  return code ? LOCALE_PACKS[code] : undefined;
}

/** {@link packTextWith} for a language tag (editor previews / placeholders). */
export function packText(lang: string, key: PackTextKey, value: string): string {
  return packTextWith(localePack(lang), key, value);
}

/** {@link packCategoryWith} for a language tag (editor previews / placeholders). */
export function packCategory(lang: string, id: string, cs: CategoryStrings): CategoryStrings {
  return packCategoryWith(localePack(lang), id, cs);
}
